    audit = conn.cur.calls[1][1]
    assert audit["action"] == "measured_remediation" and audit["details"]["rule"] == "note_314_full_block_closes_partial"
    assert sqls[2].startswith("INSERT INTO public.finding_history") and "'remediated'::history_status_t" in sqls[2]
    assert conn.cur.calls[2][1]["severity"] == "MODERATE"


