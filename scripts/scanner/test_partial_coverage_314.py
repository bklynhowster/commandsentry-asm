def test_the_probe_annotates_each_deny_with_its_block_page_315(monkeypatch, tmp_path):
    """(315) _fire_waf_differential_probe names the block page per class in the capture it
    returns, through the one library (block_page_signatures). The apex bodies: XSS ->
    wordfence_block_page, LFI -> automattic_sentries_block_page, SQLi (served) -> nothing."""
    import block_page_signatures as bps
    assert h.annotate_fired is bps.annotate_fired, "the probe uses the library's own annotator"
    outputs = {}
    def fake_run_cmd(args, timeout=None):
        url = args[-1]; sink = args[args.index("-o") + 1]
        cls = next((c for c in ("sqli", "xss", "lfi") if f"waf_probe_{c}.body" in sink), "benign")
        code, size, hdrs, body = (200, 177181, "", APEX_HOME) if cls == "benign" else APEX[cls]
        open(sink, "w").write(body)
        return 0, f"{hdrs}CS_STATUS:{code} CS_SIZE:{size} CS_TIME:0.3 CS_CONNECT:0.1", ""
    monkeypatch.setattr(h, "run_cmd", fake_run_cmd)
    monkeypatch.setattr(h.time, "sleep", lambda s: None)
    ctx = _ctx()
    baseline, payloads, details = h._fire_waf_differential_probe(ctx, tmp_path, "vpn")
    by = {f["cls"]: f for f in details["fired"]}
    assert by["xss"]["block_page"] == "wordfence_block_page"
    assert by["lfi"]["block_page"] == "automattic_sentries_block_page"
    assert "block_page" not in by["sqli"] and "block_page" not in by["benign"]
    # and a library that cannot load costs nothing but a log line
    monkeypatch.setattr(h, "annotate_fired", lambda fired: (_ for _ in ()).throw(RuntimeError("no yaml")))
    baseline, payloads, details = h._fire_waf_differential_probe(ctx, tmp_path, "vpn")
    assert all("block_page" not in f for f in details["fired"]) and len(details["fired"]) == 4


def _run_phase(monkeypatch, tmp_path, responses, *, authorized=True, live=True):
    monkeypatch.setattr(h, "_read_active_probe_policy", lambda ctx: (authorized, "vpn", ""))
    monkeypatch.setattr(h, "_ACTIVE_PROBE_LIVE", live)
    monkeypatch.setattr(h, "_write_active_probe_audit", lambda ctx, v: None)

    def fake_fire(ctx, work_dir, egress):
        baseline = h._parse_waf_probe("CS_STATUS:200 CS_SIZE:177181 CS_TIME:0.9 CS_CONNECT:0.1", APEX_HOME)
        payloads, fired = [], [{"cls": "benign", "status": 200, "size": 177181}]
        for cls, _ in h._WAF_PAYLOADS:
            code, size, hdrs, body = responses[cls]
            r = h._parse_waf_probe(f"{hdrs}CS_STATUS:{code} CS_SIZE:{size}", body, capture=True)
            r["cls"] = cls
            payloads.append(r)
            fired.append({"cls": cls, "status": code, "size": size, "body_head": body[:200]})
        return baseline, payloads, {"param": "q1a2b3c", "egress_mode": egress, "fired": fired}

    monkeypatch.setattr(h, "_fire_waf_differential_probe", fake_fire)
    ctx = _ctx()
    h.run_waf_differential_probe_phase(ctx, tmp_path)
    return ctx


def _partial(ctx):
    return [f for f in ctx.findings if h.WAF_PARTIAL_CHECK_ID in f.finding_id]


def _absent(ctx):
    return [f for f in ctx.findings if h.WAF_ABSENT_CHECK_ID in f.finding_id]


# ── the measurement ────────────────────────────────────────────────────────────
def test_passed_through_is_measured_not_inferred():
    blocked = ["lfi", "xss"]
    served = [{"cls": "sqli", "status": 200}, {"cls": "xss", "status": 403}, {"cls": "lfi", "status": 406}]
    assert h._classes_passed_through(served, blocked) == ["sqli"]
    choked = [{"cls": "sqli", "status": 500}, {"cls": "xss", "status": 403}, {"cls": "lfi", "status": 406}]
    assert h._classes_passed_through(choked, blocked) == [], "a 5xx is not a served page"
    bounced = [{"cls": "sqli", "status": 302}, {"cls": "xss", "status": 403}, {"cls": "lfi", "status": 406}]
    assert h._classes_passed_through(bounced, blocked) == [], "a redirect on one class is not a pass"
    assert h._classes_passed_through([{"cls": "ssrf-metadata", "status": 200}], []) == [], "only fired classes"
    assert h._classes_passed_through([], []) == []


def test_the_apex_shape_records_the_pass_and_emits_the_moderate_finding(monkeypatch, tmp_path):
    ctx = _run_phase(monkeypatch, tmp_path, APEX)
    m = ctx.waf_block_measured
    assert m is not None and m["blocked"] == ["lfi", "xss"] and m["passed"] == ["sqli"]
    assert ctx.waf_absence_measured is None
    fs = _partial(ctx)
    assert len(fs) == 1 and not _absent(ctx)
    f = fs[0]
    assert f.severity == "MODERATE" and f.source == "commandsentry_heavy" and f.category == "config"
    assert f.title == "WAF enforcement is partial: 1 of 3 attack classes reached the application (SQLi)"
    assert "2 were blocked (LFI, XSS)" in f.description and "1 reached the application unblocked (SQLi)" in f.description
    assert "HTTP 200" in f.description
    assert f.finding_id == stable_finding_id(ctx.asset_id, "commandsentry_heavy", h.WAF_PARTIAL_CHECK_ID, ctx.hostname)
    assert h.WAF_PARTIAL_CHECK_ID == "waf-partial-coverage"
    for word in ("Wordfence", "Automattic", "Defiant", "Pressable", "Cloud Armor", "FortiWeb"):
        assert word not in f.title and word not in f.description, "presence-only: no product named"
    art = dict((n, p) for n, _, p in ctx.artifacts)["stack_id_waf_differential"]
    assert '"passed_through": ["sqli"]' in art and '"waf_present_differential": true' in art


