# ── placement: clean path only, after regress, before history, after 310/311 ─────
def test_the_closures_run_on_the_clean_path_in_order():
    src = open(os.path.join(HERE, "run_heavy.py"), encoding="utf-8").read()
    tree = ast.parse(src)
    main = next(n for n in ast.walk(tree) if isinstance(n, ast.FunctionDef) and n.name == "run")
    body = ast.get_source_segment(src, main)
    try_block = body[:body.rindex("except DegradedRunError as dre")]
    i = [try_block.index(s) for s in (
        "regress_observed_for_scan_run(%s, %s)",
        "retract_waf_absent_on_redirect(conn, ctx, Json)",
        "close_partial_on_full_block(conn, ctx, Json)",
        "supersede_partial_on_measured_absence(conn, ctx, Json)",
        "reopen_partial_if_superseded(conn, ctx, Json)",
        "write_finding_history_for_scan_run(",
    )]
    assert i == sorted(i)
    degraded = body[body.rindex("except DegradedRunError as dre"):]
    for name in ("close_partial_on_full_block", "supersede_partial_on_measured_absence", "reopen_partial_if_superseded"):
        assert name not in degraded, "never on the degraded path"
