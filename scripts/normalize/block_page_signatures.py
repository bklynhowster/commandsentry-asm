#!/usr/bin/env python3
"""
block_page_signatures.py — the BLOCK-PAGE LIBRARY matcher (Obsidian 312, 2026-10-14).

Pure functions, no I/O beyond reading scripts/asm/artifact_signatures.yaml once.
Byte-identical in both repos.

The heavy differential probe captures every deny response it receives
(stack_id_waf_differential.details.fired[*].body_head, relay 516/531). Some deny
pages NAME THEIR OWN VENDOR — Wordfence prints "Generated by Wordfence", F5 prints
"The requested URL was rejected… Your support ID is", FortiWeb prints "Web Page
Blocked! … Attack ID". This module turns such a page into the NAME of the library
entry it matches, and nothing else: the classifier (device_class_runner) turns the
name into a vendor-identifying signal through a cited device_fingerprints.yaml row,
and the daily digest reports a deny page that matches NOTHING as unrecognized.

Rules:
  * an entry is `artifact_type: response_body_marker` with `markers_all_required`
    {headline, incident_id_any_of[]} — the headline AND at least one of the others
    must appear (relay 528: one phrase is application copy, two is the vendor);
  * matching is case-insensitive over the body with long inline base64 blobs
    stripped (relay 531: FortiWeb's markers sit behind a 38 KB inline logo);
  * a page can match MORE THAN ONE entry only by being both vendors' page, which
    no real page is; the matcher returns every match and the registry decides;
  * the vendor name NEVER comes from here — only the entry name. The vendor is
    attributed by the cited registry row (4.7 R4: no artifact->vendor mapping on
    our say-so).

Self-test: python3 scripts/normalize/block_page_signatures.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    yaml = None

_HERE = Path(__file__).resolve().parent.parent
ARTIFACT_SIGNATURES_PATH = _HERE / "asm" / "artifact_signatures.yaml"

ARTIFACT_TYPE = "response_body_marker"
OBSERVATION = "block_page_markers"   # the observation key gather_observations emits

_B64_RUN = re.compile(r"base64,[A-Za-z0-9+/=\s]{500,}")


def strip_inline_blobs(body: str) -> str:
    """Drop long inline base64 runs (images, fonts) so a vendor's text is reachable."""
    return _B64_RUN.sub("base64,<stripped>", body or "")


def load_block_page_entries(path: Path = ARTIFACT_SIGNATURES_PATH) -> list[dict]:
    """Every wired response_body_marker entry, validated to the two-marker shape."""
    if yaml is None:
        raise RuntimeError("PyYAML required to read artifact_signatures.yaml")
    data = yaml.safe_load(Path(path).read_text()) or {}
    out: list[dict] = []
    for e in data.get("artifact_signatures") or []:
        if e.get("artifact_type") != ARTIFACT_TYPE or e.get("wired") is not True:
            continue
        m = e.get("markers_all_required") or {}
        head = str(m.get("headline") or "").strip()
        others = [str(x).strip() for x in (m.get("incident_id_any_of") or []) if str(x).strip()]
        if not head or not others:
            raise ValueError(f"block-page entry {e.get('name')!r}: markers_all_required needs a "
                             "headline AND at least one incident_id_any_of marker (relay 528)")
        if not e.get("vendor"):
            raise ValueError(f"block-page entry {e.get('name')!r}: vendor required")
        cit = e.get("citation") or {}
        if not (cit.get("url") and cit.get("quote")):
            raise ValueError(f"block-page entry {e.get('name')!r}: citation url + quote required (R4)")
        out.append({"name": str(e["name"]), "vendor": e["vendor"], "product": e.get("product"),
                    "headline": head, "any_of": others})
    return out


def match_block_page(body: str, entries: list[dict] | None = None) -> list[str]:
    """Names of the library entries whose two markers BOTH appear in `body`, in
    library order. [] for an empty body or a page that names no known vendor."""
    if not body:
        return []
    entries = load_block_page_entries() if entries is None else entries
    b = strip_inline_blobs(body).lower()
    hits: list[str] = []
    for e in entries:
        if e["headline"].lower() in b and any(x.lower() in b for x in e["any_of"]):
            hits.append(e["name"])
    return hits


def is_deny(status) -> bool:
    """A probe response that is NOT a served page (2xx) and NOT a redirect (3xx): the
    shape a block page arrives in. 0 (no answer) is not a page either."""
    try:
        s = int(status or 0)
    except (TypeError, ValueError):
        return False
    return s >= 400


def scan_fired(fired: list | None, entries: list[dict] | None = None) -> dict:
    """Walk a differential artifact's details.fired list. Returns
    {"matched": [entry names, deduped, library order], "unrecognized": [{cls, status, size}, …]}
    where unrecognized = deny responses WITH a captured body that matched nothing.
    A deny with no body_head (the baseline is never captured) is skipped: nothing to read."""
    entries = load_block_page_entries() if entries is None else entries
    matched: list[str] = []
    unrecognized: list[dict] = []
    for f in fired or []:
        if not isinstance(f, dict) or not is_deny(f.get("status")):
            continue
        body = f.get("body_head")
        if not body:
            continue
        hits = match_block_page(body, entries)
        if hits:
            for h in hits:
                if h not in matched:
                    matched.append(h)
        else:
            unrecognized.append({"cls": f.get("cls"), "status": f.get("status"), "size": f.get("size")})
    return {"matched": matched, "unrecognized": unrecognized}


def annotate_fired(fired: list | None, entries: list[dict] | None = None) -> list:
    """(315) Write each deny's FIRST matching library entry onto the fired record as
    `block_page`, in place, and return the list. A deny with no body, no match, or a
    served/redirect response gets no key — the portal then says the status, never a
    guessed name. Pure apart from the in-place write; same reading rule as scan_fired."""
    entries = load_block_page_entries() if entries is None else entries
    for f in fired or []:
        if not isinstance(f, dict) or not is_deny(f.get("status")):
            continue
        body = f.get("body_head")
        if not body:
            continue
        hits = match_block_page(body, entries)
        if hits:
            f["block_page"] = hits[0]
    return fired or []


# ── 3w: GOOGLE CLOUD ARMOR, NAMED FROM WHAT IT DOES (Howie, 2026-10-30) ─────────────────
# Cloud Armor's block page names nobody (Google's 134-byte "403 Forbidden"), so the
# library above can never match it, and wafw00f's "Google Cloud App Armor" signature is
# ONLY the `Via: 1.1 google` header (wafw00f 2.4.2 plugins/gcparmor.py) — every site behind
# Google's front door carries it, armored or not (note 266). Howie, 10:03: "Why aren't we
# identifying what the damn thing is?"; 10:13 "I agree about the narrow rule"; 11:12 the
# call is Sentry's evidence, never anyone's word. The narrow rule: ONE measurement shows all
# three, or this says nothing:
#   1. Google's front door answered: every denied attack response carries `via: 1.1 google`;
#   2. the ordinary request got the real site: the benign request was served (2xx);
#   3. the attack strings got Google's own deny page at that door: at least two classes
#      denied (the differential's own bar), every deny a 403 whose body is exactly
#      Google's page below.
# Google documents the deny action as a 403/404/502 answered by the security policy, not
# the backend (artifact_signatures.yaml `cloud_armor_edge_deny`, cited). A site whose owner
# set 404 or 502 is not named by this: the safe direction. The page is matched exactly
# (whitespace and case aside): if Google ever changes it, Sentry stops naming, it never
# guesses. Howie 11:38 "A": the classifier names the product only when TWO separate deep
# scans each pass this (device_class_runner, cloud_armor_edge_deny + _earlier).
GOOGLE_EDGE_DENY_PAGE = ('<!doctype html><meta charset="utf-8"><meta name=viewport '
                         'content="width=device-width, initial-scale=1"><title>403</title>403 Forbidden')
_VIA_GOOGLE = re.compile(r"^via:[ \t]*1\.1 google[ \t]*\r?$", re.I | re.M)


def _squash(s) -> str:
    return re.sub(r"\s+", " ", str(s or "")).strip().lower()


def cloud_armor_edge_deny(fired: list | None) -> bool:
    """True iff ONE differential capture (details.fired) shows all three signs of Google
    Cloud Armor blocking at Google's front door. Pure; the rule is in the comment above."""
    rows = [f for f in (fired or []) if isinstance(f, dict)]
    benign = [f for f in rows if f.get("cls") == "benign"]
    if len(benign) != 1:
        return False
    try:
        b = int(benign[0].get("status") or 0)
    except (TypeError, ValueError):
        return False
    if not 200 <= b <= 299:
        return False
    denies = [f for f in rows if f.get("cls") != "benign" and is_deny(f.get("status"))]
    if len(denies) < 2:
        return False
    page = _squash(GOOGLE_EDGE_DENY_PAGE)
    for f in denies:
        if str(f.get("status")) != "403":
            return False
        if not _VIA_GOOGLE.search(str(f.get("raw_headers") or "")):
            return False
        if _squash(f.get("body_head")) != page:
            return False
    return True


def _selftest() -> int:
    entries = load_block_page_entries()
    names = [e["name"] for e in entries]
    ok = True
    for want in ("fortiweb_block_page", "wordfence_block_page", "automattic_sentries_block_page",
                 "cloudflare_block_page", "f5_asm_block_page"):
        if want not in names:
            print(f"FAIL: {want} not loaded"); ok = False
    wf = "<title>403 Forbidden</title><h3>About Wordfence</h3><p>Generated by Wordfence at Wed, 14 Oct 2026 9:13:10 GMT.</p>"
    if match_block_page(wf, entries) != ["wordfence_block_page"]:
        print("FAIL: wordfence page"); ok = False
    if match_block_page("<p>Generated by Wordfence</p>", entries):
        print("FAIL: one marker must not match"); ok = False
    r = scan_fired([{"cls": "benign", "status": 200}, {"cls": "xss", "status": 403, "body_head": wf},
                    {"cls": "lfi", "status": 406, "body_head": "<h1>406 Not Acceptable</h1>Not Acceptable.  Our sentries tell us that you should not be doing this."},
                    {"cls": "sqli", "status": 403, "body_head": "<h1>Forbidden</h1>nothing here", "size": 90}], entries)
    if r["matched"] != ["wordfence_block_page", "automattic_sentries_block_page"] or r["unrecognized"] != [{"cls": "sqli", "status": 403, "size": 90}]:
        print(f"FAIL: scan_fired {r}"); ok = False
    g_hdr = "HTTP/2 403 \ncontent-type: text/html; charset=UTF-8\ncontent-length: 134\nvia: 1.1 google\n"
    g = [{"cls": "benign", "status": 200, "size": 10533}] + [
        {"cls": c, "status": 403, "size": 134, "body_head": GOOGLE_EDGE_DENY_PAGE, "raw_headers": g_hdr}
        for c in ("sqli", "xss", "lfi")]
    if not cloud_armor_edge_deny(g):
        print("FAIL: 3w the uat capture must pass"); ok = False
    if cloud_armor_edge_deny([g[0], g[1]]) or cloud_armor_edge_deny([dict(g[0], status=301)] + g[1:]):
        print("FAIL: 3w one deny / a redirected baseline must not pass"); ok = False
    if cloud_armor_edge_deny(g[:3] + [dict(g[3], raw_headers="HTTP/2 403 \nserver: nginx\n")]):
        print("FAIL: 3w a deny without Google's front door must not pass"); ok = False
    print("block_page_signatures selftest:", "PASS" if ok else "FAIL", f"({len(entries)} entries)")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(_selftest())
