def test_the_loader_refuses_an_entry_with_one_marker_or_no_citation(tmp_path):
    bad = tmp_path / "sigs.yaml"
    bad.write_text("artifact_signatures:\n  - name: x\n    artifact_type: response_body_marker\n    vendor: V\n    wired: true\n"
                   "    markers_all_required: {headline: 'Blocked'}\n    citation: {url: u, quote: q}\n")
    with pytest.raises(ValueError, match="relay 528"):
        bps.load_block_page_entries(bad)
    bad.write_text("artifact_signatures:\n  - name: x\n    artifact_type: response_body_marker\n    vendor: V\n    wired: true\n"
                   "    markers_all_required: {headline: 'Blocked', incident_id_any_of: ['ID']}\n    citation: {quote: q}\n")
    with pytest.raises(ValueError, match="R4"):
        bps.load_block_page_entries(bad)


def test_the_matcher_needs_both_markers_and_names_only_the_page_it_was_given():
    assert bps.match_block_page(WORDFENCE_403) == ["wordfence_block_page"]
