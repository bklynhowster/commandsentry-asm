"""(Obsidian 312, 2026-10-14) THE BLOCK-PAGE LIBRARY — the second vendor signal.

The test case is real and recorded: commandcompanies.com, heavy scan 5e96377e, 09:13Z.
wafw00f said "generic" (a WAF, no name). The differential probe measured 2 of 3 classes
blocked and CAPTURED the two deny pages: the XSS class got a 17 KB Wordfence 403 ("About
Wordfence … Generated by Wordfence at …"); the LFI class got the Automattic edge's 406
("Our sentries tell us that you should not be doing this"), on a response that also
carried the cited x-ac: header. The SQLi class got the home page (200, unblocked).

Pins:
  * the library loads only wired response_body_marker entries, each with two markers and
    a cited url + quote (R4), and the matcher needs BOTH markers (relay 528);
  * every block_page_* registry row cites an entry whose vendor equals the row's vendor,
    and a say-so row is refused at load (validate_artifact_citations);
  * gather_observations reads the pages from the newest FIRED differential artifact,
    with the measurement, and emits the entry names as block_page_markers;
  * the apex: waf/confirmed, Automattic CONFIRMED (x-ac + the 406 page: two artifacts),
    Wordfence SUSPECTED (the page is the same artifact wafw00f reads: dedupe_key
    wafw00f_detection), and without the pages it is what it was before (hosting_edge/
    suspected) — additive;
  * uat.prodexlabs.com's Google 403 names nothing: its label does not move;
  * an unrecognized deny page is reported as such, with the page kept.
"""
