def test_annotate_fired_names_each_deny_by_its_page_and_nothing_else():
    """(315) The capture carries the name of the block page per class, so the portal can
    say WHO refused each attack. Same reading rule as scan_fired: denies with a body only;
    a served page, a redirect, a bodiless deny and an unknown page get no name."""
    fired = [{"cls": "benign", "status": 200, "size": 177181},
             {"cls": "sqli", "status": 200, "size": 177181, "body_head": "<title>Home</title>"},
             {"cls": "xss", "status": 403, "size": 17006, "body_head": WORDFENCE_403},
             {"cls": "lfi", "status": 406, "size": 1156, "body_head": SENTRIES_406},
             {"cls": "log4shell-param", "status": 403, "size": 134, "body_head": GOOGLE_403},
             {"cls": "ssrf-metadata", "status": 403, "size": 15},
             {"cls": "bounce", "status": 301, "size": 162, "body_head": "<title>301 Moved Permanently</title>"}]
    out = bps.annotate_fired(fired)
    assert out is fired, "in place: the record the artifact writes is the record annotated"
    assert [f.get("block_page") for f in fired] == [None, None, "wordfence_block_page", "automattic_sentries_block_page", None, None, None]
    assert bps.annotate_fired([]) == [] and bps.annotate_fired(None) == []
    # scan_fired and annotate_fired agree on what is recognized
    assert bps.scan_fired(fired)["matched"] == ["wordfence_block_page", "automattic_sentries_block_page"]


def test_every_block_page_row_cites_an_entry_with_the_same_vendor_and_is_high():
    fps, th = load_fingerprints(), load_thresholds()
    rows = [fp for fp in fps if fp.get("observation") == "block_page_markers"]
    assert {r["signal"] for r in rows} == {"block_page_wordfence", "block_page_automattic", "block_page_cloudflare",
                                           "block_page_f5", "block_page_fortiweb"}
    sigs = load_artifact_signatures()
    for r in rows:
        assert r["evidence_class"] == "vendor_identifying" and r["match_semantic"] == "exact"
        assert th["weight"][r["signal"]] == "high"
        for name in r["match_values"]:
            assert sigs[name]["vendor"] == r["vendor_product"]["vendor"], r["signal"]
    assert validate_artifact_citations(fps) == []


def test_a_say_so_block_page_row_is_refused():
    fps = load_fingerprints()
    bogus = {"signal": "block_page_palo_alto", "observation": "block_page_markers", "match_semantic": "exact",
             "match_values": ["palo_alto_block_page"], "device_class": "edge_firewall",
             "evidence_class": "vendor_identifying", "vendor_product": {"vendor": "Palo Alto Networks"}}
    errs = validate_artifact_citations(fps + [bogus])
    assert errs and "palo_alto_block_page" in errs[0] and "R4" in errs[0]


def test_dedupe_keys_follow_the_artifacts_wafw00f_reads():
    """wafw00f's plugins match the FortiWeb, Wordfence, Cloudflare and F5 pages, so those
    rows share its key: they NAME the vendor but are not a second independent tell. The
    Automattic 406 has no wafw00f plugin: its own key."""
    by = {fp["signal"]: fp for fp in load_fingerprints() if fp.get("observation") == "block_page_markers"}
    for s in ("block_page_wordfence", "block_page_cloudflare", "block_page_f5", "block_page_fortiweb"):
        assert by[s]["dedupe_key"] == "wafw00f_detection", s
    assert by["block_page_automattic"]["dedupe_key"] == "block_page_automattic"


