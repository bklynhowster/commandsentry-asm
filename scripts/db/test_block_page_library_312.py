def _fired(pages):
    """A details.fired list in the collector's shape: benign first, then the classes."""
    out = [{"cls": "benign", "status": 200, "size": 177181}]
    for cls, status, body in pages:
        e = {"cls": cls, "status": status, "size": len(body) if body else 0}
        if body is not None:
            e["body_head"] = body
        out.append(e)
    return out


