# ── the apex, end to end ──────────────────────────────────────────────────────
def _apex_arts(with_pages=True):
    fired = APEX_FIRED if with_pages else _fired([("sqli", 200, None), ("xss", 403, None), ("lfi", 406, None)])
    return {ART: [(_diff(True, ["lfi", "xss"], fired), NOW)],
            "stack_id_wafw00f": [(_wafw00f("generic"), NOW)],
            "stack_id_passive": [(_passive(APEX_HEADERS), NOW)]}


def test_the_apex_names_both_vendors_automattic_confirmed_wordfence_suspected():
    fps, th = load_fingerprints(), load_thresholds()
    r = classify(_obs(_apex_arts()), fps, th)
    assert (r["device_class"], r["device_class_confidence"]) == ("waf", "confirmed")
    vendors = {v["vendor"]: v for v in r["vendor_product"]["vendors"]}
    assert set(vendors) == {"Automattic", "Defiant"}
    assert vendors["Automattic"] == {"vendor": "Automattic", "device_class": "hosting_edge", "confidence": "confirmed"}, \
        "x-ac header + the 406 page: two artifacts, one vendor"
    assert vendors["Defiant"] == {"vendor": "Defiant", "product": "Wordfence", "device_class": "waf", "confidence": "suspected"}, \
        "the page is the artifact wafw00f reads: named, not corroborated"
    sigs = {e["signal"] for e in r["evidence"]}
    assert {"block_page_wordfence", "block_page_automattic", "waf_present_wafw00f", "waf_present_differential",
            "automattic_x_ac_edge_cache_header"} <= sigs


def test_without_the_pages_the_apex_is_what_it_was_before_312():
    """Additive: the same capture read without its pages classifies exactly as before."""
    fps, th = load_fingerprints(), load_thresholds()
    r = classify(_obs(_apex_arts(with_pages=False)), fps, th)
    assert (r["device_class"], r["device_class_confidence"]) == ("hosting_edge", "suspected")
    assert r["vendor_product"] == {"vendor": "Automattic"} and r["vendor_product_confidence"] == "suspected"


