def _diff(verdict, blocked=(), fired=None):
    return json.dumps({"schema": 1, "probe_class": "waf_differential",
                       "waf_present_differential": verdict, "blocked": list(blocked), "reason": "",
                       "details": {"live_flag": verdict is not None, "baseline_status": 200,
                                   "fired": fired if fired is not None else []}})


def _wafw00f(kind="generic"):
    return json.dumps({"schema": 1, "wafw00f_kind": kind, "wafw00f_detected": True})


def _passive(headers):
    return json.dumps({"schema": 1, "headers": headers, "set_cookie_names": []})


